/**
  ******************************************************************************
  * @file    gamesnake.h
  * @brief   贪吃蛇小游戏（0.96" SSD1306 OLED + 无线手柄控制）
  *
  *          操作（无线手柄，见 gamepad.h）：
  *            A 按键   确定 / 开始游戏
  *            X 按键   退出游戏（返回主界面）
  *            B 按键   暂停 / 继续
  *            十字键 / 左摇杆   控制移动方向
  *
  *          界面：
  *            顶部 1 行（y=0..7） 显示 "SCORE xxx"
  *            游戏区 16 x 7 格（每格 8x8 像素）
  *
  *          边界：无边界模式——蛇从一侧穿出、从对侧穿入（穿墙）。
  *          仅撞到自己（或蛇身满格）时游戏结束。
  ******************************************************************************
  */

#ifndef __GAMESNAKE_H
#define __GAMESNAKE_H

#include "stm32f10x.h"

/*============================== 游戏参数 ===============================*/
#define SNAKE_GRID_COLS         16      /* 每行格数 */
#define SNAKE_GRID_ROWS         7       /* 行数（顶部 1 行留作分数） */
#define SNAKE_CELL_PX           8       /* 每格像素 */

/* 蛇移动周期（ms） */
#define SNAKE_TICK_MS           200

/*============================= 公共接口 =================================*/

/**
  * @brief  运行贪吃蛇游戏（阻塞，直到 X 退出或 GAME OVER 后 X 返回）
  * @note   内部读取无线手柄（USART1），需先调用 Gamepad_Init()
  */
void Snake_Run(void);

#endif /* __GAMESNAKE_H */
